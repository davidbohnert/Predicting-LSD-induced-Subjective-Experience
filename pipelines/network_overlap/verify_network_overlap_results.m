function verify_network_overlap_results(outputPath, expectedIterations)
%VERIFY_NETWORK_OVERLAP_RESULTS Audit the S16 numerical outputs.
if nargin < 2 || isempty(expectedIterations), expectedIterations = 10000; end
resultsPath = fullfile(outputPath, 'joint_edge_overlap_results.csv');
nullPath = fullfile(outputPath, 'joint_edge_overlap_null_statistics.csv');
assert(isfile(resultsPath) && isfile(nullPath), ...
    'CPM:OverlapVerify:MissingOutput', 'Required overlap CSV output is missing.');
results = readtable(resultsPath, 'TextType', 'string');
nulls = readtable(nullPath, 'TextType', 'string');
assert(height(results) == 6, 'CPM:OverlapVerify:ResultRows', ...
    'Expected three outcome pairs at each of two thresholds.');
assert(all(ismember([0.01 0.05], unique(results.EdgeThreshold))), ...
    'CPM:OverlapVerify:Thresholds', 'Expected thresholds .01 and .05.');
assert(all(results.SharedEdges >= 0) && all(results.Dice >= 0 & results.Dice <= 1), ...
    'CPM:OverlapVerify:EffectSizes', 'Invalid overlap effect size.');
assert(height(nulls) == expectedIterations, ...
    'CPM:OverlapVerify:NullRows', ...
    'Null table does not contain one row per permutation.');
fprintf('Verified %d overlap rows and %d null rows.\n', ...
    height(results), height(nulls));
end
